package com.example.library.service;

import com.example.library.entity.Book;
import com.example.library.repository.BookRepository;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import java.util.List;
import java.util.Optional;

/**
 * BookService - Business Logic Layer
 * 
 * This service class contains the business logic for book-related operations.
 * It acts as an intermediary between the Controller (HTTP requests) 
 * and Repository (database operations).
 * 
 * @Service - Marks this class as a Spring service component
 *            (manages business logic and transactions)
 */
@Service
public class BookService {

    /**
     * BookRepository instance injected by Spring
     * @Autowired - Automatically creates and injects the repository bean
     * This allows us to perform database operations without creating instances manually
     */
    @Autowired
    private BookRepository bookRepository;

    // ==================== CRUD Operations ====================

    /**
     * Retrieve all books from the database
     * 
     * @return List<Book> - List of all books in the library
     *         Returns empty list if no books exist
     */
    public List<Book> getAllBooks() {
        System.out.println("Fetching all books from database...");
        return bookRepository.findAll();
    }

    /**
     * Retrieve a single book by its ID
     * 
     * @param bookId - The ID of the book to retrieve
     * @return Optional<Book> - Contains the book if found, empty otherwise
     *         Optional prevents NullPointerException
     */
    public Optional<Book> getBookById(Long bookId) {
        System.out.println("Fetching book with ID: " + bookId);
        
        if (bookId == null || bookId <= 0) {
            System.out.println("Invalid book ID provided");
            return Optional.empty();
        }
        
        return bookRepository.findById(bookId);
    }

    /**
     * Add a new book to the database
     * 
     * @param book - The Book object to save
     * @return Book - The saved book object (with generated ID)
     * 
     * Note: If book.bookId is null, it will be auto-generated by database
     *       If bookId exists, it will update the existing book
     */
    public Book addBook(Book book) {
        System.out.println("Adding new book: " + book.getTitle());
        
        if (book == null) {
            System.out.println("Book object is null");
            return null;
        }
        
        if (book.getTitle() == null || book.getTitle().isEmpty()) {
            System.out.println("Book title is required");
            return null;
        }
        
        if (book.getAuthor() == null || book.getAuthor().isEmpty()) {
            System.out.println("Book author is required");
            return null;
        }
        
        // Set default available count if not provided
        if (book.getAvailableCount() <= 0) {
            book.setAvailableCount(1);
        }
        
        Book savedBook = bookRepository.save(book);
        System.out.println("Book saved successfully with ID: " + savedBook.getBookId());
        return savedBook;
    }

    /**
     * Update an existing book
     * 
     * @param bookId - The ID of the book to update
     * @param bookDetails - The Book object containing updated information
     * @return Book - The updated book object, or null if book not found
     */
    public Book updateBook(Long bookId, Book bookDetails) {
        System.out.println("Updating book with ID: " + bookId);
        
        if (bookId == null || bookId <= 0) {
            System.out.println("Invalid book ID provided");
            return null;
        }
        
        Optional<Book> existingBook = bookRepository.findById(bookId);
        
        if (existingBook.isPresent()) {
            Book book = existingBook.get();
            
            // Update fields if provided (non-null)
            if (bookDetails.getTitle() != null && !bookDetails.getTitle().isEmpty()) {
                book.setTitle(bookDetails.getTitle());
            }
            
            if (bookDetails.getAuthor() != null && !bookDetails.getAuthor().isEmpty()) {
                book.setAuthor(bookDetails.getAuthor());
            }
            
            if (bookDetails.getCategory() != null && !bookDetails.getCategory().isEmpty()) {
                book.setCategory(bookDetails.getCategory());
            }
            
            if (bookDetails.getAvailableCount() > 0) {
                book.setAvailableCount(bookDetails.getAvailableCount());
            }
            
            Book updatedBook = bookRepository.save(book);
            System.out.println("Book updated successfully: " + updatedBook.getTitle());
            return updatedBook;
        } else {
            System.out.println("Book not found with ID: " + bookId);
            return null;
        }
    }

    /**
     * Delete a book by its ID
     * 
     * @param bookId - The ID of the book to delete
     * @return boolean - true if deletion successful, false otherwise
     */
    public boolean deleteBook(Long bookId) {
        System.out.println("Deleting book with ID: " + bookId);
        
        if (bookId == null || bookId <= 0) {
            System.out.println("Invalid book ID provided");
            return false;
        }
        
        if (bookRepository.existsById(bookId)) {
            bookRepository.deleteById(bookId);
            System.out.println("Book deleted successfully with ID: " + bookId);
            return true;
        } else {
            System.out.println("Book not found with ID: " + bookId);
            return false;
        }
    }

}
